export const createProductSlug = (name: string): string => {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
};

export const getProductBySlug = (slug: string): Product | undefined => {
  return PRODUCTS.find((p) => createProductSlug(p.name) === slug);
};

